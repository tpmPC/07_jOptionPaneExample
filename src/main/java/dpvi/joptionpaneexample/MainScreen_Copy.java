    private boolean ValidateForm()
    {
        String name = jTextFieldName.getText();
        
        if( name == null || "".equals(name))
        {
            JOptionPane.showMessageDialog(this, "Name field cannot be ampty", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }        
        String age = jTextFieldAge.getText();
        try{
            Integer.valueOf(age);
        }
        catch(NumberFormatException n)
        {
            JOptionPane.showMessageDialog(this, "Age has to be an int number", "Age Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }
    
